export const MAINS = Object.keys(EQUITES);

export function equiteDe(main, scenario) {
  const v = EQUITES[main];
  return v ? v[scenario.index] : null;
}

// Rang de la main dans ce scénario, de 1 (la meilleure) à 169. Sert au retour après réponse :
// « 61 % » ne dit rien tout seul, « 61 %, 14e main sur 169 » situe.
export function rangDe(main, scenario) {
  const cible = equiteDe(main, scenario);
  if (cible == null) return null;
  let rang = 1;
  for (const m of MAINS) if (EQUITES[m][scenario.index] > cible) rang++;
  return rang;
}

